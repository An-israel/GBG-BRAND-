/**
 * Finds every place "DBS" appears in the store's data and writes docs/DBS_AUDIT.md
 * with a suggested action for each (update / archive / delete / keep). Read-only.
 *
 *   npm run audit:dbs
 *
 * Covers: store name & sender email, products, collections, pages, blog articles, menus,
 * redirects and metafields. Apps, email automations, notification templates, checkout
 * branding, social/Meta integrations and the favicon cannot be read via the API: they are
 * listed as a manual checklist in the same file.
 */
import fs from 'node:fs';
import { parseArgs } from './lib/args.js';
import { loadConfig } from './lib/config.js';
import { createLogger } from './lib/logger.js';
import { ShopifyClient } from './lib/shopify.js';

parseArgs();
const log = createLogger('dbs-audit');
const client = new ShopifyClient(loadConfig(), { logger: log });
const RE = /\bdbs\b|dbs\s*accessories|gbg\s*wholesale\s*hub/i;
type Hit = { area: string; item: string; where: string; snippet: string; action: string };
const hits: Hit[] = [];
const snip = (s: string) => { const m = s.match(RE); if (!m) return ''; const i = m.index ?? 0; return s.slice(Math.max(0, i - 40), i + 60).replace(/\s+/g, ' ').replace(/\|/g, '/'); };
const check = (area: string, item: string, fields: Record<string, string | null | undefined>, action: string) => {
  for (const [where, v] of Object.entries(fields)) if (v && RE.test(v)) hits.push({ area, item, where, snippet: snip(v), action });
};

async function main() {
  const shop = (await client.query(`query { shop { name email contactEmail description } }`)).shop;
  check('Store', shop.name, { 'store name': shop.name, 'sender email': shop.email, 'contact email': shop.contactEmail, 'meta description': shop.description }, 'UPDATE in Settings → Store details');

  for await (const p of client.paginate<any>(`query($after: String) { products(first: 100, after: $after) { pageInfo { hasNextPage endCursor } edges { node { title handle status vendor tags descriptionHtml seo { title description } } } } }`, ['products'])) {
    const old = p.status !== 'ACTIVE';
    check('Product', `${p.title} (${p.handle}, ${p.status})`, { title: p.title, vendor: p.vendor, tags: p.tags.join(','), description: p.descriptionHtml, 'SEO title': p.seo?.title, 'SEO description': p.seo?.description, handle: p.handle },
      old ? 'ARCHIVE (not for GBG) – never delete products with order history' : 'UPDATE wording, or ARCHIVE if not part of the GBG catalogue');
  }
  for await (const c of client.paginate<any>(`query($after: String) { collections(first: 100, after: $after) { pageInfo { hasNextPage endCursor } edges { node { title handle descriptionHtml seo { title description } } } } }`, ['collections'])) {
    check('Collection', `${c.title} (${c.handle})`, { title: c.title, description: c.descriptionHtml, 'SEO title': c.seo?.title, 'SEO description': c.seo?.description, handle: c.handle }, 'UPDATE or DELETE (add a redirect if it had traffic)');
  }
  for await (const p of client.paginate<any>(`query($after: String) { pages(first: 100, after: $after) { pageInfo { hasNextPage endCursor } edges { node { title handle body } } } }`, ['pages'])) {
    check('Page', `${p.title} (${p.handle})`, { title: p.title, body: p.body, handle: p.handle }, 'UPDATE, or replace with the new GBG page and redirect');
  }
  for await (const b of client.paginate<any>(`query($after: String) { articles(first: 100, after: $after) { pageInfo { hasNextPage endCursor } edges { node { title handle body blog { title } } } } }`, ['articles'])) {
    check('Blog article', `${b.blog?.title} › ${b.title}`, { title: b.title, body: b.body }, 'UPDATE or hide (unpublish)');
  }
  const menus = (await client.query(`query { menus(first: 50) { nodes { handle title items { title url items { title url items { title url } } } } } }`)).menus.nodes;
  const walk = (menu: string, items: any[]) => items.forEach((i) => { check('Menu', `${menu} › ${i.title}`, { title: i.title, url: i.url }, 'UPDATE (setup-store.ts rebuilds menus)'); walk(menu, i.items || []); });
  menus.forEach((m: any) => { check('Menu', m.title, { title: m.title }, 'UPDATE'); walk(m.handle, m.items); });
  for await (const r of client.paginate<any>(`query($after: String) { urlRedirects(first: 250, after: $after) { pageInfo { hasNextPage endCursor } edges { node { path target } } } }`, ['urlRedirects'])) {
    check('Redirect', r.path, { path: r.path, target: r.target }, 'KEEP if it sends old DBS links to GBG pages');
  }

  const rows = hits.map((h) => `| ${h.area} | ${h.item.replace(/\|/g, '/')} | ${h.where} | ${h.snippet} | ${h.action} | ☐ |`).join('\n');
  const md = `# DBS audit – ${new Date().toISOString().slice(0, 10)}

Generated by \`npm run audit:dbs\` (read-only). Every place the old brand ("DBS", "DBS Accessories", "GBG Wholesale Hub") appears.
Actions: **update / archive / delete / keep**. Tick the last column when done. Never delete historical orders, refunds or finance records.

## Found automatically (${hits.length})

| Area | Item | Field | Text found | Suggested action | Done |
|---|---|---|---|---|---|
${rows || '| – | Nothing found | | | | |'}

## Check by hand (the API cannot read these)

| Area | Where to look | Suggested action | Done |
|---|---|---|---|
| Installed apps | Settings → Apps and sales channels | List each app + monthly cost in docs/HANDOVER.md; remove unused | ☐ |
| Email automations / marketing | Marketing → Automations; Shopify Email templates | Update sender name, logo, wording; pause DBS campaigns | ☐ |
| Notification templates | Settings → Notifications (all templates) | Replace with notifications/*.liquid from this repo | ☐ |
| Sender name & email | Settings → Notifications → Sender email | GBG Bargain Shop / [TO CONFIRM email] | ☐ |
| Checkout branding | Settings → Checkout → Customize | GBG logo, navy/gold colours | ☐ |
| Customer account pages | Settings → Customer accounts → Customize | GBG logo and colours | ☐ |
| Favicon & social preview | Online Store → Themes → Customize → Theme settings → Brand and logo | GBG favicon + default social image | ☐ |
| Store name & legal name | Settings → Store details | GBG Bargain Shop / [TO CONFIRM legal entity] | ☐ |
| Social / Meta integrations | Facebook & Instagram channel, Google & YouTube channel, TikTok | Reconnect to GBG accounts or disconnect | ☐ |
| Discount codes | Discounts | Expire DBS-only codes | ☐ |
| Policies | Settings → Policies | Replace with content/policies drafts once approved | ☐ |
| Gift card template, packing slips, invoices | Settings → Shipping and delivery → Packing slip template | Update logo and name | ☐ |
| Old domain | Settings → Domains | Keep connected and redirecting to www.gbgbargainshop.co.uk | ☐ |
| Google Business Profile, Search Console | External | Update website URL | ☐ |
`;
  fs.mkdirSync('docs', { recursive: true });
  fs.writeFileSync('docs/DBS_AUDIT.md', md);
  log.info(`${hits.length} occurrence(s) found. Written to docs/DBS_AUDIT.md`);
}
main().catch((e) => { log.error(e.message); process.exit(1); });
